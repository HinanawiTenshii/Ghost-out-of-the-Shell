#if UNITY_EDITOR
using System;
using System.Linq;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;

public static partial class LevelVisualRollout
{
    public static void RefreshWallRims()
    {
        Isolate(); contact=AssetDatabase.LoadAssetAtPath<Material>(Art+"/Contact.mat");
        foreach(var path in Scenes)
        {
            var scene=EditorSceneManager.OpenScene(path);
            var profile=scene.GetRootGameObjects().Select(r=>r.GetComponent<LevelSceneVisualProfile>()).Single(p=>p!=null);
            var walls=scene.GetRootGameObjects().SelectMany(r=>r.GetComponentsInChildren<SpriteRenderer>(true)).Where(Wall).ToArray();
            foreach(var filter in profile.GetComponentsInChildren<MeshFilter>(true))
            {
                if(!AssetDatabase.GetAssetPath(filter.sharedMesh).StartsWith(Art+"/"+scene.name+"/Wall_")||filter.GetComponent<Collider2D>())throw new Exception("Unexpected geometry in profile: "+filter.name);
                UnityEngine.Object.DestroyImmediate(filter.gameObject);
            }
            BakeWalls(profile.transform,walls,Art+"/"+scene.name,Theme(scene.name));
            var used=profile.GetComponentsInChildren<MeshFilter>(true).Select(f=>AssetDatabase.GetAssetPath(f.sharedMesh)).ToArray();
            // Only obsolete meshes generated by this rollout in this scene's private art directory.
            foreach(var obsolete in System.IO.Directory.GetFiles(Art+"/"+scene.name,"Wall_*.asset").Select(p=>p.Replace('\\','/')))
                if(!used.Contains(obsolete))AssetDatabase.DeleteAsset(obsolete);
            EditorSceneManager.MarkSceneDirty(scene);EditorSceneManager.SaveScene(scene);AssetDatabase.SaveAssets();
            Debug.Log("LEVEL_WALL_REPAIR_PASS "+scene.name+" originalTransforms=unchanged diagonals=none");
        }
    }
}
#endif
